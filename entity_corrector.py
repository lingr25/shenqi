def correct_text(text: str, file_tag: str = "") -> str:
    """对单段文本应用机制与干员专有名词纠错"""
    res = text
    for pattern, repl in CORRECTION_RULES:
        res = re.sub(pattern, repl, res)
    if file_tag:
        for key, rules in FILE_CONTEXT_RULES.items():
            if file_tag.startswith(key):
                for pattern, repl in rules:
                    res = re.sub(pattern, repl, res)
                break
    return res

def clean_subtitle_items(items, file_tag: str = ""):
    """
    清洗字幕条目列表：
    - 应用专有名词纠错规则
    - 计算规范持续时长
    """
    cleaned = []
    for it in items:
        raw_c = it.get('content', '').strip()
        if not raw_c:
            continue
        norm_c = correct_text(raw_c, file_tag)
        cleaned.append({
            "from": it.get('from'),
            "to": it.get('to'),
            "duration": round(it.get('to', 0) - it.get('from', 0), 2),
            "content": norm_c
        })
    return cleaned

def format_timestamp(seconds: float) -> str:
    """将秒数转为 [HH:MM:SS] 或 [MM:SS]"""
    s = int(seconds)
    hours = s // 3600
    minutes = (s % 3600) // 60
    secs = s % 60
    if hours > 0:
        return f"[{hours:02d}:{minutes:02d}:{secs:02d}]"
    else:
        return f"[{minutes:02d}:{secs:02d}]"

def build_natural_transcript(cleaned_items, max_pause=1.2, max_len=60, file_tag: str = ""):
    """
    将碎句字幕进行自然断句与时间符合并：
    - 停顿小于 max_pause 秒且总字数不超过 max_len 时平滑合并
    - 过滤纯单字无意义结巴或空停顿
    - 行首保留规范时间戳
    """
    if not cleaned_items:
        return []

    lines = []
    current_start = cleaned_items[0]['from']
    current_end = cleaned_items[0]['to']
    current_tokens = [cleaned_items[0]['content']]

    for it in cleaned_items[1:]:
        t_from = it['from']
        t_to = it['to']
        text = it['content']
        
        # 停顿间隔
        pause = t_from - current_end
        combined_len = sum(len(t) for t in current_tokens) + len(text)
        
        if pause <= max_pause and combined_len <= max_len:
            current_tokens.append(text)
            current_end = t_to
        else:
            merged_text = correct_text(" ".join(current_tokens), file_tag)
            lines.append(f"{format_timestamp(current_start)} {merged_text}")
            current_start = t_from
            current_end = t_to
            current_tokens = [text]

    if current_tokens:
        merged_text = correct_text(" ".join(current_tokens), file_tag)
        lines.append(f"{format_timestamp(current_start)} {merged_text}")

    return lines
